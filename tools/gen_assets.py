def glyph_rows(ch: str):
    """Six bytes per glyph: 6 pixels across, bit 5 leftmost, bit 6 set."""
    rows = list(GLYPHS.get(ch, ("00000",) * 7))
    out = []
    for r in range(8):
        if r < 7:
            bits = rows[r]
            v = 0
            for i, b in enumerate(bits):
                if b == "1":
                    v |= 0x20 >> i
        else:
            v = 0
        out.append(0x40 | v)
    return out


def write_font(path: str) -> None:
    lines = ["; generated by tools/gen_assets.py - do not edit",
             "        .export font_data", "        .segment \"RODATA\"", "font_data:"]
    for code in range(32, 128):
        ch = chr(code)
        rows = glyph_rows(ch)
        lines.append("        .byte " + ",".join("$%02X" % b for b in rows)
                     + "        ; '%s'" % (ch if ch not in '"\\' else "?"))
    # pad out to a whole page multiple so the copy loop is simple
    lines.append("        .byte " + ",".join(["$40"] * 256))
    open(path, "w").write("\n".join(lines) + "\n")


def write_tables(path: str) -> None:
    lines = ["; generated by tools/gen_assets.py - do not edit",
             "        .export xtab, xbit", "        .segment \"RODATA\"", "xtab:"]
    xtab = [x // 6 for x in range(240)]
    xbit = [0x20 >> (x % 6) for x in range(240)]
    for i in range(0, 240, 20):
        lines.append("        .byte " + ",".join("%d" % v for v in xtab[i:i + 20]))
    lines.append("xbit:")
    for i in range(0, 240, 20):
        lines.append("        .byte " + ",".join("$%02X" % v for v in xbit[i:i + 20]))
    open(path, "w").write("\n".join(lines) + "\n")


def main() -> int:
    os.makedirs(DATA, exist_ok=True)
    write_font(os.path.join(DATA, "font.s"))
    write_tables(os.path.join(DATA, "tables.s"))
    print("wrote data/font.s, data/tables.s")
    return 0


